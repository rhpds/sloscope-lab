"""Controlled sample workload: real local HTTP requests, counters and handler latency."""
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
import json
import os
import threading
import time

NAMESPACE = os.environ['POD_NAMESPACE']
BUCKETS = (.005,.01,.025,.05,.1,.25,.5,1.0,2.5,5.0)
LOCK=threading.Lock()
COUNTS={'200':0,'503':0}
HIST={b:0 for b in BUCKETS}
COUNT=0
SUM=0.0
SEQUENCE=0

def phase():
    try:
        value=Path(os.environ.get('SLOSCOPE_SCENARIO_FILE','/scenario/phase')).read_text().strip()
    except OSError:
        value='baseline'
    return value if value in ('baseline','regression','recovery') else 'baseline'

def metrics():
    labels=f'service="checkout-api",namespace="{NAMESPACE}"'
    with LOCK:
        lines=['# TYPE http_requests_total counter']
        for code,value in COUNTS.items():
            lines.append(f'http_requests_total{{{labels},code="{code}"}} {value}')
        lines.append('# TYPE http_request_duration_seconds histogram')
        for boundary,value in HIST.items():
            lines.append(f'http_request_duration_seconds_bucket{{{labels},le="{boundary}"}} {value}')
        lines.append(f'http_request_duration_seconds_bucket{{{labels},le="+Inf"}} {COUNT}')
        lines.append(f'http_request_duration_seconds_count{{{labels}}} {COUNT}')
        lines.append(f'http_request_duration_seconds_sum{{{labels}}} {SUM:.9f}')
    return ('\n'.join(lines)+'\n').encode()

class Handler(BaseHTTPRequestHandler):
    def log_message(self,*args):
        pass
    def respond(self,status,body,content_type='application/json'):
        self.send_response(status)
        self.send_header('Content-Type',content_type)
        self.send_header('Content-Length',str(len(body)))
        self.end_headers()
        self.wfile.write(body)
    def do_GET(self):
        global COUNT,SUM,SEQUENCE
        if self.path=='/metrics':
            return self.respond(200,metrics(),'text/plain; version=0.0.4')
        if self.path=='/health':
            return self.respond(200,b'{"status":"ok","workload":"controlled-checkout"}')
        if self.path=='/phase':
            return self.respond(200,json.dumps({'phase':phase(),'controlled_lab_workload':True}).encode())
        if self.path!='/checkout':
            return self.respond(404,b'{"detail":"not found"}')
        current=phase()
        with LOCK:
            SEQUENCE+=1
            sequence=SEQUENCE
        # Controlled failures/delay are generated by this lab workload, not a production incident.
        divisor=7 if current=='regression' else 50
        status=503 if sequence%divisor==0 else 200
        delay=(.15,.25,.40)[sequence%3] if current=='regression' else (.01,.02,.03)[sequence%3]
        started=time.perf_counter()
        time.sleep(delay)
        elapsed=time.perf_counter()-started
        with LOCK:
            COUNTS[str(status)]+=1
            COUNT+=1
            SUM+=elapsed
            for boundary in BUCKETS:
                if elapsed<=boundary:
                    HIST[boundary]+=1
        return self.respond(status,json.dumps({'phase':current,'controlled_lab_workload':True,'status':status}).encode())

if __name__=='__main__':
    ThreadingHTTPServer(('0.0.0.0',8081),Handler).serve_forever()
